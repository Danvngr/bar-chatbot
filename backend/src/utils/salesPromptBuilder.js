const DEFAULT_PRODUCT_NAME = "בוט AI למסעדות";

function parseDemoRestaurantData(rawValue) {
  const fallback = {
    name: "ביסטרו הדגמה",
    hours: "א-ה 12:00-23:00, שישי 12:00-16:00",
    menu: "https://example.com/menu",
    reservation: "אפשר להזמין בטלפון 03-5551234",
    kosher: "כשר חלבי",
  };

  const text = String(rawValue || "").trim();
  if (!text) return fallback;

  try {
    const parsed = JSON.parse(text);
    if (!parsed || typeof parsed !== "object") return fallback;
    return {
      name: String(parsed.name || fallback.name),
      hours: String(parsed.hours || fallback.hours),
      menu: String(parsed.menu || fallback.menu),
      reservation: String(parsed.reservation || fallback.reservation),
      kosher: String(parsed.kosher || fallback.kosher),
    };
  } catch (_error) {
    return fallback;
  }
}

